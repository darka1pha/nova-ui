/**
 * Writes token-derived CSS into src/styles/generated/ so the Tailwind build
 * of styles.css and the components share one source of truth: @darkalpha/nova-tokens.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  cssBlock,
  defaultTheme,
  getResolvedTheme,
  presets,
  staticVariables,
  derivedVariables,
  THEME_ROOT_SELECTOR,
  COLOR_SCHEME_CSS,
  tailwindThemeCss,
  themeCss,
  themeVariables,
} from "@darkalpha/nova-tokens";

const dir = fileURLToPath(new URL("../src/styles/generated/", import.meta.url));
mkdirSync(dir, { recursive: true });
const header = "/* Generated by scripts/generate-css.ts from @darkalpha/nova-tokens — do not edit. */\n";
// light-dark() values are also declared on the outermost theme root, where color-scheme is set.
// Natively they'd resolve the same from :root, but CSS pipelines that lower light-dark() for older
// browsers (Lightning CSS, which Tailwind v4 runs) resolve it where it's declared, and only theme
// roots carry the switch: declared on :root alone, system mode got "#fff#1a1510" for every color.
const OUTER_THEME_ROOT = ":where(.nv-theme, [data-nv-theme]):not(:where(.nv-theme, [data-nv-theme]) *)";
const schemeDependent = (vars: Record<string, string>) => Object.fromEntries(Object.entries(vars).filter(([, value]) => value.includes("light-dark(")));

writeFileSync(`${dir}theme.css`, header + tailwindThemeCss());
writeFileSync(
  `${dir}tokens.css`,
  header +
    "@layer theme {\n" +
    cssBlock(":where(:root)", { ...staticVariables(), ...themeVariables(getResolvedTheme(defaultTheme)) }) +
    cssBlock(OUTER_THEME_ROOT, schemeDependent({ ...staticVariables(), ...themeVariables(getResolvedTheme(defaultTheme)) })) +
    cssBlock(THEME_ROOT_SELECTOR, derivedVariables()) +
    COLOR_SCHEME_CSS +
    "}\n",
);
writeFileSync(
  `${dir}themes.css`,
  header + "@layer theme {\n" + Object.values(presets).map((t) => themeCss(getResolvedTheme(t))).join("\n") + "}\n",
);
console.log("Generated token CSS");
