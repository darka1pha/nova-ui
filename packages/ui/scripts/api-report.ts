/**
 * Lists every public export of @darkalpha/nova-ui and @darkalpha/nova-tokens,
 * per package entry, into api-report.md. The file is committed, so any change
 * to the public API shows up in review; `--check` (run in CI) fails when the
 * report is out of date. Reads the built .d.ts files: run `pnpm build` first.
 *
 *   node scripts/api-report.ts           # rewrite api-report.md
 *   node scripts/api-report.ts --check   # fail if it would change
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const here = dirname(fileURLToPath(import.meta.url));
const packages = [resolve(here, ".."), resolve(here, "../../tokens")];
const reportFile = resolve(here, "../api-report.md");

interface Entry {
  label: string;
  file: string;
}

function entries(pkgDir: string): Entry[] {
  const pkg = JSON.parse(readFileSync(resolve(pkgDir, "package.json"), "utf8")) as { name: string; exports: Record<string, string | { types?: string }> };
  const out: Entry[] = [];
  for (const [subpath, target] of Object.entries(pkg.exports)) {
    const types = typeof target === "object" ? target.types : undefined;
    if (!types) continue;
    out.push({ label: subpath === "." ? pkg.name : `${pkg.name}/${subpath.replace(/^\.\//, "")}`, file: resolve(pkgDir, types) });
  }
  return out;
}

const all = packages.flatMap(entries);
const missing = all.filter((e) => !existsSync(e.file));
if (missing.length) throw new Error(`Build first; missing ${missing.map((e) => e.file).join(", ")}`);

const program = ts.createProgram(
  all.map((e) => e.file),
  { module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX, skipLibCheck: true, noEmit: true },
);
const checker = program.getTypeChecker();

const sections: string[] = [];
let total = 0;
for (const entry of all) {
  const source = program.getSourceFile(entry.file);
  const symbol = source && checker.getSymbolAtLocation(source);
  if (!symbol) throw new Error(`Can't read exports of ${entry.file}`);
  const values: string[] = [];
  const types: string[] = [];
  for (const exp of checker.getExportsOfModule(symbol)) {
    const target = exp.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exp) : exp;
    (target.flags & ts.SymbolFlags.Value ? values : types).push(exp.name);
  }
  values.sort((a, b) => a.localeCompare(b));
  types.sort((a, b) => a.localeCompare(b));
  total += values.length + types.length;
  sections.push(
    [
      `## \`${entry.label}\``,
      "",
      `${values.length} values, ${types.length} types.`,
      "",
      "### Values",
      "",
      values.map((n) => `- \`${n}\``).join("\n") || "_none_",
      "",
      "### Types",
      "",
      types.map((n) => `- \`${n}\``).join("\n") || "_none_",
    ].join("\n"),
  );
}

const report = [
  "# Public API report",
  "",
  "Generated by `packages/ui/scripts/api-report.ts` from the built type declarations. Don't edit it by hand:",
  "run `pnpm api:report` after changing an export, and review the diff. A removed or renamed",
  "name is a breaking change (a major release after 1.0).",
  "",
  `${total} exports across ${all.length} entries.`,
  "",
  sections.join("\n\n"),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(reportFile) ? readFileSync(reportFile, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== report) {
    console.error("api-report.md is out of date: the public API changed. Run `pnpm api:report` and commit the result.");
    process.exit(1);
  }
  console.log(`API report is current (${total} exports).`);
} else {
  writeFileSync(reportFile, report);
  console.log(`Wrote api-report.md (${total} exports across ${all.length} entries).`);
}
