/**
 * Regenerates src/primitives/colors.ts from hand-picked seed colors.
 * Run with: node scripts/generate-primitives.ts
 *
 * The output is committed so primitive tokens are literal, reviewable values.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { generateScale, type ScaleKind } from "../src/color/palette.ts";

const seeds: Record<string, { seed: string; kind?: ScaleKind; hueShift?: number; note: string }> = {
  violet: { seed: "#6d4aff", note: "Vivid violet — default brand" },
  blue: { seed: "#2563ff", note: "Electric blue" },
  sky: { seed: "#0ea5e9", note: "Clear sky blue" },
  cyan: { seed: "#06b6d4", note: "Bright cyan" },
  teal: { seed: "#0fb5a6", note: "Fresh teal" },
  mint: { seed: "#2fd49c", note: "Fresh mint" },
  green: { seed: "#1f9d55", note: "Natural green — success" },
  lime: { seed: "#84cc16", note: "Zesty lime" },
  amber: { seed: "#f5a524", hueShift: -12, note: "Sunny amber — warning" },
  gold: { seed: "#c9a13b", note: "Muted gold — premium accents" },
  orange: { seed: "#ff7a1a", note: "Energetic orange" },
  coral: { seed: "#ff6b57", note: "Energetic coral — default accent" },
  red: { seed: "#e5383b", note: "Signal red — danger" },
  pink: { seed: "#ec4899", note: "Warm pink" },
  magenta: { seed: "#c026d3", note: "Bold magenta" },
  sand: { seed: "#8a7f73", kind: "neutral", note: "Warm neutral" },
  stone: { seed: "#7d8075", kind: "neutral", note: "Natural, slightly green neutral" },
  slate: { seed: "#677489", kind: "neutral", note: "Cool neutral" },
  gray: { seed: "#777777", kind: "neutral", note: "Pure neutral" },
  ink: { seed: "#5a6290", kind: "neutral", note: "Deep blue-violet neutral — midnight surfaces" },
};

let out = `// Generated by scripts/generate-primitives.ts — do not edit by hand.
import type { ColorScale } from "../color/palette.ts";

`;
const names: string[] = [];
for (const [name, { seed, kind = "chromatic", hueShift, note }] of Object.entries(seeds)) {
  const scale = generateScale(seed, { kind, anchor: kind === "chromatic", hueShift: hueShift ?? 0 });
  names.push(name);
  out += `/** ${note}. Seed ${seed}. */\nexport const ${name}: ColorScale = ${JSON.stringify(scale, null, 2).replace(/"(\d+)":/g, "$1:")};\n\n`;
}
out += `export const white = "#ffffff";\nexport const black = "#000000";\n\n`;
out += `export const palette = { ${names.join(", ")} } as const;\nexport type PaletteName = keyof typeof palette;\n`;

writeFileSync(fileURLToPath(new URL("../src/primitives/colors.ts", import.meta.url)), out);
console.log(`Wrote ${names.length} scales`);
